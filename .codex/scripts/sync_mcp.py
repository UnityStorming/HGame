"""将共享 MCP JSON 同步为 Codex TOML，保留其他设置及 Codex 专用选项。"""

import argparse
import json
import os
from pathlib import Path
import re
import sys
import tempfile

try:
    import tomllib
except ImportError:
    try:
        import tomli as tomllib
    except ImportError:
        sys.exit("Python < 3.11 requires: python -m pip install -r .codex/scripts/requirements.txt")


BEGIN = "# >>> HGame shared MCP >>>"
END = "# <<< HGame shared MCP <<<"
PORTABLE = {"command", "args", "env", "url", "headers", "type"}
TOML_PORTABLE = {"command", "args", "env", "url", "http_headers"}


def load_servers(path):
    data = json.loads(path.read_text(encoding="utf-8-sig"))
    servers = data.get("mcpServers")
    if not isinstance(servers, dict):
        raise ValueError("mcpServers must be an object")
    result = {}
    for name, server in servers.items():
        if not name or not isinstance(server, dict):
            raise ValueError("Each MCP server needs a name and an object")
        unknown = set(server) - PORTABLE
        if unknown:
            raise ValueError("Unsupported shared MCP fields: " + ", ".join(sorted(unknown)))
        if ("command" in server) == ("url" in server):
            raise ValueError("Each MCP server needs exactly one command or url")
        transport = server.get("type")
        if transport not in (None, "stdio", "http"):
            raise ValueError("Shared MCP supports stdio or Streamable HTTP; bridge SSE with mcp_proxy")
        if transport == "stdio" and "command" not in server or transport == "http" and "url" not in server:
            raise ValueError("MCP type does not match command/url")
        for field in ("command", "url"):
            if field in server and (not isinstance(server[field], str) or not server[field].strip()):
                raise ValueError(field + " must be a nonempty string")
        if "args" in server and (not isinstance(server["args"], list) or not all(isinstance(v, str) for v in server["args"])):
            raise ValueError("args must be an array of strings")
        for field in ("env", "headers"):
            if field in server and (not isinstance(server[field], dict) or not all(isinstance(v, str) for v in server[field].values())):
                raise ValueError(field + " must be a string map")
        result[name] = {("http_headers" if key == "headers" else key): value
                        for key, value in server.items() if key != "type"}
    return result


def toml_value(value):
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(toml_value(key) + " = " + toml_value(item) for key, item in value.items()) + " }"
    raise ValueError("Unsupported TOML value: " + type(value).__name__)


def without_mcp_tables(text):
    text = re.sub(r"(?ms)^" + re.escape(BEGIN) + r"\r?\n.*?^" + re.escape(END) + r"\r?\n?", "", text)
    headers = list(re.finditer(r"(?m)^[ \t]*\[\[?[^\r\n]+?\]\]?[ \t]*(?:#[^\r\n]*)?$", text))
    chunks = [text[:headers[0].start()] if headers else text]
    for index, header in enumerate(headers):
        end = headers[index + 1].start() if index + 1 < len(headers) else len(text)
        chunk = text[header.start():end]
        if "mcp_servers" not in tomllib.loads(header.group(0)):
            chunks.append(chunk)
            continue
        # 表尾的注释可能说明下一个 hooks 表，保留这些注释和空行。
        lines = chunk.splitlines(keepends=True)
        trailing = len(lines)
        while trailing and (not lines[trailing - 1].strip() or lines[trailing - 1].lstrip().startswith("#")):
            trailing -= 1
        chunks.extend(lines[trailing:])
    return "".join(chunks).lstrip("\r\n")


def sync(root, check=False):
    path = root / ".codex/config.toml"
    original = path.read_text(encoding="utf-8-sig") if path.exists() else ""
    before = tomllib.loads(original)
    existing = before.get("mcp_servers", {})
    shared = load_servers(root / ".codex/mcp.json")
    desired = {}
    for name, server in shared.items():
        native = {key: value for key, value in existing.get(name, {}).items() if key not in TOML_PORTABLE}
        desired[name] = {**server, **native}
    if existing == desired:
        return True
    if check:
        return False
    lines = [BEGIN, "# Generated by .codex/scripts/sync_mcp.py; edit .codex/mcp.json for shared fields."]
    for name, server in desired.items():
        lines.append("[mcp_servers." + toml_value(name) + "]")
        lines.extend(toml_value(key) + " = " + toml_value(value) for key, value in server.items())
        lines.append("")
    lines.append(END)
    # 根级设置必须位于第一个表头前，生成表追加到原有配置末尾。
    remaining = without_mcp_tables(original).rstrip("\r\n")
    updated = (remaining + "\n\n" if remaining else "") + "\n".join(lines) + "\n"
    after = tomllib.loads(updated)
    if {key: value for key, value in before.items() if key != "mcp_servers"} != {key: value for key, value in after.items() if key != "mcp_servers"}:
        raise ValueError("Sync would change non-MCP settings; no files were written")
    if after.get("mcp_servers", {}) != desired:
        raise ValueError("Generated MCP configuration does not match source")
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent, delete=False) as handle:
        temp = Path(handle.name)
        handle.write(updated)
    try:
        os.replace(temp, path)
    finally:
        if temp.exists():
            temp.unlink()
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--check", action="store_true", help="Read-only drift check")
    args = parser.parse_args()
    try:
        if not sync(args.root.resolve(), args.check):
            print("MCP drift detected; run python .codex/scripts/sync_mcp.py", file=sys.stderr)
            return 1
    except (OSError, ValueError, TypeError) as error:
        print(str(error), file=sys.stderr)
        return 1
    print("MCP configuration matches .codex/mcp.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
